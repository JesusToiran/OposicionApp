	private boolean schemaExists(String schemaName) {
		Boolean exists = jdbcTemplate.queryForObject(
				"select exists (select 1 from information_schema.schemata where schema_name = ?)",
				Boolean.class,
				schemaName);
		return Boolean.TRUE.equals(exists);
	}

	private Boolean[] roleAdminFlags(String roleName) {
		return roleAdminFlags(postgres, roleName);
	}

	private static Boolean[] roleAdminFlags(PostgreSQLContainer container, String roleName) {
		JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
				container,
				container.getUsername(),
				container.getPassword());
		return adminJdbcTemplate.queryForObject(
				"select rolsuper, rolcreatedb, rolcreaterole, rolreplication, rolbypassrls from pg_roles where rolname = ?",
				(resultSet, rowNumber) -> new Boolean[] {
						resultSet.getBoolean("rolsuper"),
						resultSet.getBoolean("rolcreatedb"),
						resultSet.getBoolean("rolcreaterole"),
						resultSet.getBoolean("rolreplication"),
						resultSet.getBoolean("rolbypassrls")
				},
				roleName);
	}

	private Integer roleMemberships(String roleName) {
		return jdbcTemplate.queryForObject(
				"select count(*) from pg_auth_members membership join pg_roles member on member.oid = membership.member where member.rolname = ?",
				Integer.class,
				roleName);
	}

	private Boolean schemaCreatePrivilege(String roleName, String schemaName) {
		return schemaCreatePrivilege(postgres, roleName, schemaName);
	}

	private Boolean databaseCreatePrivilege(String roleName) {
		return jdbcTemplate.queryForObject(
				"select has_database_privilege(?, current_database(), 'CREATE')",
				Boolean.class,
				roleName);
	}

	private static Boolean schemaCreatePrivilege(PostgreSQLContainer container, String roleName, String schemaName) {
		JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
				container,
				container.getUsername(),
				container.getPassword());
		return adminJdbcTemplate.queryForObject(
				"select has_schema_privilege(?, ?, 'CREATE')",
				Boolean.class,
				roleName,
				schemaName);
	}

	private static Map<String, Object> flywayHistory(PostgreSQLContainer container) {
		JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
				container,
				container.getUsername(),
				container.getPassword());
		return adminJdbcTemplate.queryForMap(
				"select version, description, type, script, checksum, success from flyway_schema_history where version = '1'");
	}

	private Boolean tableSelectPrivilege(String roleName, String schemaName, String tableName) {
		return jdbcTemplate.queryForObject(
				"select has_table_privilege(?, format('%I.%I', ?, ?), 'SELECT')",
				Boolean.class,
				roleName,
				schemaName,
				tableName);
	}

	private String typeOwner(String schemaName, String typeName) {
		return jdbcTemplate.queryForObject(
				"select r.rolname from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_roles r on r.oid = t.typowner where n.nspname = ? and t.typname = ?",
				String.class,
				schemaName,
				typeName);
	}

	private static boolean roleExists(JdbcTemplate jdbcTemplate, String roleName) {
		Boolean exists = jdbcTemplate.queryForObject(
				"select exists (select 1 from pg_roles where rolname = ?)",
				Boolean.class,
				roleName);
		return Boolean.TRUE.equals(exists);
	}

	private static JdbcTemplate jdbcTemplateForRole(
			PostgreSQLContainer container,
			String username,
			String password) {
		DriverManagerDataSource dataSource = new DriverManagerDataSource();
		dataSource.setUrl(container.getJdbcUrl());
		dataSource.setUsername(username);
		dataSource.setPassword(password);
		return new JdbcTemplate(dataSource);
	}

	private static void bootstrapRoles(PostgreSQLContainer container) {
		executeAdminSql(container, bootstrapSqlFor(container));
	}

	private static void executeAdminSql(PostgreSQLContainer container, String sql) {
		try (var connection = DriverManager.getConnection(
				container.getJdbcUrl(),
				container.getUsername(),
				container.getPassword());
				Statement statement = connection.createStatement()) {
			statement.execute(sql);
		}
		catch (SQLException ex) {
			throw new CannotGetJdbcConnectionException("Could not bootstrap PostgreSQL roles", ex);
		}
	}

	private static String bootstrapSqlFor(PostgreSQLContainer container) {
		return readBootstrapSql()
				.replace(":\"POSTGRES_DB\"", quoteIdentifier(container.getDatabaseName()));
	}

	private static void setRolePasswords(
			PostgreSQLContainer container,
			String appPassword,
			String migratorPassword) {
		JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
				container,
				container.getUsername(),
				container.getPassword());
		adminJdbcTemplate.execute("alter role oposicionapp_app with password '" + sqlLiteral(appPassword) + "'");
		adminJdbcTemplate.execute("alter role oposicionapp_migrator with password '" + sqlLiteral(migratorPassword) + "'");
	}

	private static String quoteIdentifier(String identifier) {
		return "\"" + identifier.replace("\"", "\"\"") + "\"";
	}

	private static String sqlLiteral(String value) {
		return value.replace("'", "''");
	}

	private static void assertSqlState(Throwable throwable, String sqlState) {
		Throwable current = throwable;
		while (current != null) {
			if (current instanceof PSQLException psqlException) {
				assertThat(psqlException.getSQLState()).isEqualTo(sqlState);
				return;
			}
			current = current.getCause();
		}
		throw new AssertionError("No PostgreSQL exception found", throwable);
	}

	private static String readBootstrapSql() {
		try (InputStream inputStream = OposicionAppApplicationTests.class.getResourceAsStream(
				"/db/bootstrap/postgresql_roles.sql")) {
			if (inputStream == null) {
				throw new IllegalStateException("Bootstrap SQL not found");
			}
			return new String(inputStream.readAllBytes(), StandardCharsets.UTF_8);
		}
		catch (IOException ex) {
			throw new IllegalStateException("Could not read bootstrap SQL", ex);
		}
	}

