	@Test
	void documentedPsqlInvocationRunsBootstrapWithIdentifierVariable() throws Exception {
		try (PostgreSQLContainer psqlDatabase = new PostgreSQLContainer("postgres:18")) {
			psqlDatabase.start();
			psqlDatabase.copyFileToContainer(
					Transferable.of(readBootstrapSql().getBytes(StandardCharsets.UTF_8)),
					"/tmp/postgresql_roles.sql");

			ExecResult result = psqlDatabase.execInContainer(
					"psql",
					"-U",
					psqlDatabase.getUsername(),
					"-d",
					psqlDatabase.getDatabaseName(),
					"-v",
					"ON_ERROR_STOP=1",
					"-v",
					"POSTGRES_DB=" + psqlDatabase.getDatabaseName(),
					"-f",
					"/tmp/postgresql_roles.sql");

			assertThat(result.getExitCode()).isZero();
			assertThat(roleExists(
					jdbcTemplateForRole(psqlDatabase, psqlDatabase.getUsername(), psqlDatabase.getPassword()),
					"oposicionapp_app")).isTrue();
		}
	}

	@Test
	void migratorKeepsTemporaryPublicCreateUntilAdministrativeFinalization() {
		try (PostgreSQLContainer freshDatabase = new PostgreSQLContainer("postgres:18")) {
			freshDatabase.start();

			String freshMigratorPassword = UUID.randomUUID().toString();
			bootstrapRoles(freshDatabase);
			setRolePasswords(freshDatabase, UUID.randomUUID().toString(), freshMigratorPassword);

			assertThat(schemaCreatePrivilege(freshDatabase, "oposicionapp_migrator", "public")).isTrue();

			Flyway.configure()
					.dataSource(freshDatabase.getJdbcUrl(), "oposicionapp_migrator", freshMigratorPassword)
					.locations("classpath:db/migration")
					.load()
					.migrate();

			assertThat(schemaCreatePrivilege(freshDatabase, "oposicionapp_migrator", "public")).isTrue();

			bootstrapRoles(freshDatabase);

			assertThat(schemaCreatePrivilege(freshDatabase, "oposicionapp_migrator", "public")).isFalse();
		}
	}

	@Test
	void bootstrapRunsTransactionallyAndStopsOnErrors() {
		try (PostgreSQLContainer failingDatabase = new PostgreSQLContainer("postgres:18")) {
			failingDatabase.start();

			String brokenBootstrap = bootstrapSqlFor(failingDatabase)
					.replace(
							"ALTER ROLE oposicionapp_app WITH LOGIN",
							"SELECT 1 / 0;\nALTER ROLE oposicionapp_app WITH LOGIN");

			assertThatThrownBy(() -> executeAdminSql(failingDatabase, brokenBootstrap))
					.hasRootCauseInstanceOf(SQLException.class);

			JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
					failingDatabase,
					failingDatabase.getUsername(),
					failingDatabase.getPassword());
			assertThat(roleExists(adminJdbcTemplate, "oposicionapp_app")).isFalse();
			assertThat(roleExists(adminJdbcTemplate, "oposicionapp_migrator")).isFalse();
		}
	}

