	@Test
	void flywayCreatesInitialSchemas() {
		assertThat(schemaExists("core")).isTrue();
		assertThat(schemaExists("c1_tai")).isTrue();
		assertThat(schemaExists("study")).isTrue();

		Integer installedRank = jdbcTemplateForRole(postgres, "oposicionapp_migrator", migratorPassword).queryForObject(
				"select installed_rank from flyway_schema_history where version = '1' and success = true",
				Integer.class);

		assertThat(installedRank).isNotNull();
	}

	@Test
	void applicationRoleCanUseDataButCannotChangeStructure() {
		JdbcTemplate migratorJdbcTemplate = jdbcTemplateForRole(
				postgres,
				"oposicionapp_migrator",
				migratorPassword);

		migratorJdbcTemplate.execute(
				"create table core.permission_probe (id integer generated by default as identity primary key, label text not null)");

		jdbcTemplate.update("insert into core.permission_probe (label) values (?)", "probe");
		assertThat(jdbcTemplate.queryForObject("select label from core.permission_probe where id = 1", String.class))
				.isEqualTo("probe");

		jdbcTemplate.update("update core.permission_probe set label = ? where id = 1", "updated");
		jdbcTemplate.update("delete from core.permission_probe where id = 1");

		assertThatThrownBy(() -> jdbcTemplate.execute("create table core.app_forbidden (id integer)"))
				.satisfies(throwable -> assertSqlState(throwable, "42501"));
		assertThatThrownBy(() -> jdbcTemplate.execute("drop table core.permission_probe"))
				.satisfies(throwable -> assertSqlState(throwable, "42501"));

		migratorJdbcTemplate.execute("drop table core.permission_probe");
	}

	@Test
	void databaseRolesDoNotHaveAdministrativePrivileges() {
		assertThat(roleAdminFlags("oposicionapp_app")).containsExactly(false, false, false, false, false);
		assertThat(roleAdminFlags("oposicionapp_migrator")).containsExactly(false, false, false, false, false);
		assertThat(schemaCreatePrivilege("oposicionapp_app", "public")).isFalse();
		assertThat(roleMemberships("oposicionapp_app")).isZero();
		assertThat(roleMemberships("oposicionapp_migrator")).isZero();
	}

	@Test
	void bootstrapSupportsDatabaseWithExistingV1AppliedByPostgres() {
		try (PostgreSQLContainer existingDatabase = new PostgreSQLContainer("postgres:18")) {
			existingDatabase.start();

			Flyway.configure()
					.dataSource(existingDatabase.getJdbcUrl(), existingDatabase.getUsername(), existingDatabase.getPassword())
					.locations("classpath:db/migration")
					.load()
					.migrate();

			JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
					existingDatabase,
					existingDatabase.getUsername(),
					existingDatabase.getPassword());
			adminJdbcTemplate.execute("create table core.existing_probe (id integer primary key, label text not null)");
			adminJdbcTemplate.update("insert into core.existing_probe (id, label) values (1, 'kept')");
			Map<String, Object> originalHistory = flywayHistory(existingDatabase);

			String existingAppPassword = UUID.randomUUID().toString();
			String existingMigratorPassword = UUID.randomUUID().toString();
			bootstrapRoles(existingDatabase);
			setRolePasswords(existingDatabase, existingAppPassword, existingMigratorPassword);

			Flyway.configure()
					.dataSource(existingDatabase.getJdbcUrl(), "oposicionapp_migrator", existingMigratorPassword)
					.locations("classpath:db/migration")
					.load()
					.migrate();

			JdbcTemplate existingAppJdbcTemplate = jdbcTemplateForRole(
					existingDatabase,
					"oposicionapp_app",
					existingAppPassword);
			JdbcTemplate existingMigratorJdbcTemplate = jdbcTemplateForRole(
					existingDatabase,
					"oposicionapp_migrator",
					existingMigratorPassword);

			bootstrapRoles(existingDatabase);

			assertThat(existingAppJdbcTemplate.queryForObject("select count(*) from core.existing_probe", Integer.class))
					.isEqualTo(1);
			assertThat(existingAppJdbcTemplate.queryForObject("select label from core.existing_probe where id = 1", String.class))
					.isEqualTo("kept");
			assertThat(flywayHistory(existingDatabase)).containsAllEntriesOf(originalHistory);
			assertThat(schemaCreatePrivilege(existingDatabase, "oposicionapp_migrator", "public")).isFalse();
			assertThat(existingMigratorJdbcTemplate.queryForObject(
					"select tableowner from pg_tables where schemaname = 'core' and tablename = 'existing_probe'",
					String.class)).isEqualTo("oposicionapp_migrator");
		}
	}

	@Test
	void bootstrapCanBeRepeatedWithoutLosingExistingData() {
		JdbcTemplate migratorJdbcTemplate = jdbcTemplateForRole(
				postgres,
				"oposicionapp_migrator",
				migratorPassword);

		migratorJdbcTemplate.execute("create table core.repeat_probe (id integer primary key, label text not null)");
		jdbcTemplate.update("insert into core.repeat_probe (id, label) values (?, ?)", 1, "kept");

		bootstrapRoles(postgres);

		assertThat(jdbcTemplate.queryForObject("select label from core.repeat_probe where id = 1", String.class))
				.isEqualTo("kept");
		assertThat(schemaCreatePrivilege("oposicionapp_migrator", "public")).isFalse();

		migratorJdbcTemplate.execute("drop table core.repeat_probe");
	}

	@Test
	void bootstrapNormalizesExistingApplicationRolePrivilegesInsideProjectScope() {
		JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
				postgres,
				postgres.getUsername(),
				postgres.getPassword());
		adminJdbcTemplate.execute("grant create on database \"" + postgres.getDatabaseName() + "\" to oposicionapp_app");
		adminJdbcTemplate.execute("grant create on schema core to oposicionapp_app");
		adminJdbcTemplate.execute("grant select on table public.flyway_schema_history to oposicionapp_app");

		bootstrapRoles(postgres);

		assertThat(databaseCreatePrivilege("oposicionapp_app")).isFalse();
		assertThat(schemaCreatePrivilege("oposicionapp_app", "core")).isFalse();
		assertThat(tableSelectPrivilege("oposicionapp_app", "public", "flyway_schema_history")).isFalse();
	}

	@Test
	void bootstrapChangesIndependentCompositeTypeOwnerWithoutTouchingTableRowTypes() {
		JdbcTemplate adminJdbcTemplate = jdbcTemplateForRole(
				postgres,
				postgres.getUsername(),
				postgres.getPassword());
		adminJdbcTemplate.execute("create type core.address_probe as (street text, number integer)");
		adminJdbcTemplate.execute("create table core.type_probe (id integer primary key)");

		assertThat(typeOwner("core", "address_probe")).isEqualTo(postgres.getUsername());
		assertThat(typeOwner("core", "type_probe")).isEqualTo(postgres.getUsername());

		bootstrapRoles(postgres);
		bootstrapRoles(postgres);

		assertThat(typeOwner("core", "address_probe")).isEqualTo("oposicionapp_migrator");
		assertThat(typeOwner("core", "type_probe")).isEqualTo("oposicionapp_migrator");

		jdbcTemplateForRole(postgres, "oposicionapp_migrator", migratorPassword)
				.execute("drop table core.type_probe");
		jdbcTemplateForRole(postgres, "oposicionapp_migrator", migratorPassword)
				.execute("drop type core.address_probe");
	}

